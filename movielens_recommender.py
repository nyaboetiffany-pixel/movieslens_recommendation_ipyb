# ---- metrics ----------------------------------------------------------------
def rating_metrics(S, df, mask=None):
    "S = users x items matrix of predicted ratings"
    p = np.clip(S[df.u.values, df.i.values], 0.5, 5.0); y = df.rating.values
    if mask is not None: p, y = p[mask], y[mask]
    return float(np.sqrt(np.mean((y - p) ** 2))), float(np.mean(np.abs(y - p)))

def ranking_metrics(S, train_df, test_df, k=5, thr=4.0, min_support=0):
    S = S.copy().astype(np.float32)
    S[train_df.u.values, train_df.i.values] = -np.inf                 # never re-recommend seen movies
    n_train = np.bincount(train_df.i.values, minlength=n_items)
    if min_support: S[:, n_train < min_support] = -np.inf
    top = np.argpartition(-S, k, axis=1)[:, :k]
    order = np.argsort(-np.take_along_axis(S, top, 1), axis=1)
    top = np.take_along_axis(top, order, 1)
    rel = test_df[test_df.rating >= thr].groupby("u").i.apply(set)
    P, R, N = [], [], []
    disc = 1 / np.log2(np.arange(2, k + 2))
    for u, rs in rel.items():
        hit = np.array([x in rs for x in top[u]], dtype=float)
        P.append(hit.sum() / k); R.append(hit.sum() / len(rs))
        N.append((hit * disc).sum() / disc[:min(len(rs), k)].sum())
    return dict(P5=np.mean(P), R5=np.mean(R), NDCG5=np.mean(N),
                coverage=len(np.unique(top[list(rel.index)])),
                avg_pop=float(n_train[top[list(rel.index)]].mean()))

"""## 4. Collaborative filtering models

All models output a full **users × movies matrix of predicted ratings**, which makes both rating-prediction and top-N ranking trivial to evaluate.

1. **Bias baseline** – `r̂ᵤᵢ = μ + bᵤ + bᵢ`, with regularised (shrunk) user and item biases. Captures "generous raters" and "universally liked movies".
2. **Item-based kNN** – for the target movie, take the user's ratings on the *k* most similar movies (cosine similarity of bias-removed rating columns, **shrunk** by the number of co-raters so that similarities built on 1–2 users are not trusted) and add the weighted average residual to the bias baseline.
3. **Matrix factorization (ALS)** – learn k-dimensional latent vectors for users and movies on the residuals left by the bias model (`r̂ᵤᵢ = μ + bᵤ + bᵢ + pᵤ·qᵢ`) using alternating least squares with ridge regularisation.
"""

def fit_bias(df, lam_i=10., lam_u=15., iters=10):
    u, i, r = df.u.values, df.i.values, df.rating.values; mu = r.mean()
    b_u, b_i = np.zeros(n_users), np.zeros(n_items)
    for _ in range(iters):
        b_i = np.bincount(i, r - mu - b_u[u], n_items) / (lam_i + np.bincount(i, minlength=n_items))
        b_u = np.bincount(u, r - mu - b_i[i], n_users) / (lam_u + np.bincount(u, minlength=n_users))
    return mu, b_u, b_i

def bias_scores(bias):
    mu, b_u, b_i = bias
    return (mu + b_u[:, None] + b_i[None, :]).astype(np.float32)

# ---------------- item-based kNN ------------------------------------------
def knn_cache(df, bias):
    mu, b_u, b_i = bias
    res = df.rating.values - (mu + b_u[df.u.values] + b_i[df.i.values])
    shape = (n_users, n_items)
    E = sparse.csr_matrix((res.astype(np.float32), (df.u.values, df.i.values)), shape=shape)
    B = sparse.csr_matrix((np.ones(len(df), np.float32), (df.u.values, df.i.values)), shape=shape)
    dot = (E.T @ E).toarray().astype(np.float32)
    nrm = np.sqrt(np.asarray(E.multiply(E).sum(0)).ravel()).astype(np.float32) + 1e-9
    cos = dot / nrm[:, None] / nrm[None, :]; del dot
    co = (B.T @ B).toarray().astype(np.float32)
    return dict(E=E, B=B, cos=cos, co=co)

def knn_scores(cache, bias, k=40, shrink=25., damp=1.0):
    S = cache["cos"] * (cache["co"] / (cache["co"] + shrink))
    np.fill_diagonal(S, 0)
    drop = np.argpartition(-np.abs(S), k, axis=1)[:, k:]
    np.put_along_axis(S, drop, 0, axis=1)                    # keep top-k neighbours per movie
    St = np.ascontiguousarray(S.T)
    num = cache["E"] @ St
    den = cache["B"] @ np.abs(St)
    return bias_scores(bias) + (num / (den + damp)).astype(np.float32)

# ---------------- matrix factorization (ALS on residuals) -------------------
def _als_step(X, F, lam):
    out = np.zeros((X.shape[0], F.shape[1]), dtype=np.float64); reg = lam * np.eye(F.shape[1])
    for a in range(X.shape[0]):
        s, e = X.indptr[a], X.indptr[a + 1]
        if s == e: continue
        Fj = F[X.indices[s:e]]
        out[a] = np.linalg.solve(Fj.T @ Fj + reg, Fj.T @ X.data[s:e])
    return out

def fit_mf(df, bias, k=30, lam=8., iters=12, seed=SEED):
    mu, b_u, b_i = bias
    res = df.rating.values - (mu + b_u[df.u.values] + b_i[df.i.values])
    Rr = sparse.csr_matrix((res, (df.u.values, df.i.values)), shape=(n_users, n_items)); Rc = Rr.T.tocsr()
    g = np.random.default_rng(seed)
    P, Q = g.normal(0, .1, (n_users, k)), g.normal(0, .1, (n_items, k))
    for _ in range(iters):
        P = _als_step(Rr, Q, lam); Q = _als_step(Rc, P, lam)
    return P, Q

def mf_scores(bias, P, Q):
    return bias_scores(bias) + (P @ Q.T).astype(np.float32)

# ---- hyper-parameter tuning on the VALIDATION set (RMSE) --------------------
