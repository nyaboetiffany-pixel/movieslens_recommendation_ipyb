"""## 5. Hybrid model — content-based filtering for the cold-start problem

Collaborative filtering has nothing to say about a movie with 0–3 ratings. We therefore build a **content profile** for every movie from:

* **Genres** (TF-IDF over the genre list) and the **release decade** parsed from the title;
* **User-generated tags** (`tags.csv`, TF-IDF over tag text; available for a subset of movies).

A **user taste profile** is the average of the content vectors of the movies they rated, weighted by *(rating − their mean rating)* (so liked movies pull the profile towards them and disliked ones push away). Cosine similarity between the profile and each movie gives a content score, standardised per user (`zᵤᵢ`).

**Blend.** The more ratings a movie has, the more we trust collaborative filtering:

`r̂ᵤᵢ(hybrid) = r̂ᵤᵢ(MF) + s · λᵢ · zᵤᵢ`, with `λᵢ = c / (c + nᵢ)` where `nᵢ` is the number of training ratings of movie *i*.

A movie with no ratings gets the full content signal (`λ = 1`); a blockbuster with 300 ratings gets almost none. `s` (strength) and `c` (trust constant) are tuned on the validation set.
"""

# ---- content features -------------------------------------------------------
mv = movies.set_index("movieId").reindex(items)
year = mv.title.str.extract(r"\((\d{4})\)\s*$")[0].astype(float)
decade = ("decade" + (year // 10 * 10).fillna(0).astype(int).astype(str))
genre_txt = mv.genres.fillna("").str.replace("(no genres listed)", "nogenre", regex=False) + "|" + decade
tag_txt = tags.assign(tag=tags.tag.astype(str).str.lower()).groupby("movieId").tag.apply(" ".join).reindex(items).fillna("")

Xg = TfidfVectorizer(token_pattern=r"[^|]+", lowercase=True).fit_transform(genre_txt)
Xt = TfidfVectorizer(stop_words="english", min_df=2, sublinear_tf=True).fit_transform(tag_txt)
X = normalize(sparse.hstack([Xg * 1.0, Xt * 0.6]).tocsr())          # item x feature (L2-normalised rows)
print("content matrix:", X.shape, "| movies with tags:", int((tag_txt.str.len() > 0).sum()))

def content_z(df):
    "per-user standardised cosine similarity between taste profile and every movie (users x items)"
    um = df.groupby("u").rating.mean().reindex(range(n_users)).values
    w = df.rating.values - um[df.u.values]
    W = sparse.csr_matrix((w, (df.u.values, df.i.values)), shape=(n_users, n_items))
    prof = normalize((W @ X).toarray())
    sim = (X @ prof.T).T                                              # users x items
    return ((sim - sim.mean(1, keepdims=True)) / (sim.std(1, keepdims=True) + 1e-9)).astype(np.float32)

def hybrid_scores(S_mf, Z, n_item_train, s, c):
    lam_i = c / (c + n_item_train)
    return S_mf + (s * lam_i)[None, :].astype(np.float32) * Z

n_tr = np.bincount(train.i.values, minlength=n_items)
P, Q = fit_mf(train, bias_tr, **BEST_MF); S_mf_val = mf_scores(bias_tr, P, Q)
Z_tr = content_z(train)
cold_val = n_tr[val.i.values] <= 5
print(f"validation ratings on cold movies (<=5 train ratings): {cold_val.sum():,} ({cold_val.mean():.1%})")

hy_grid = []
for s in (0.1, 0.2, 0.4, 0.6):
    for c in (5, 20, 50):
        S_h = hybrid_scores(S_mf_val, Z_tr, n_tr, s, c)
        hy_grid.append((s, c, *rating_metrics(S_h, val), rating_metrics(S_h, val, cold_val)[0]))
hy_grid = pd.DataFrame(hy_grid, columns=["s", "c", "RMSE_all", "MAE_all", "RMSE_cold"]).sort_values("RMSE_all")
print("MF alone  RMSE all / cold:", [round(x, 4) for x in (rating_metrics(S_mf_val, val)[0], rating_metrics(S_mf_val, val, cold_val)[0])])
display(hy_grid.head(6).round(4))
BEST_HY = dict(s=float(hy_grid.iloc[0].s), c=float(hy_grid.iloc[0].c)); print("best hybrid:", BEST_HY)

"""## 6. Final evaluation on the held-out **test** set

Every model is re-fitted on train + validation with the tuned hyper-parameters, then scored once on the test set. Two non-personalised baselines are added for context: **Random** and **Popularity** (rank by number of training ratings).
"""

def fit_everything(df, label=""):
    bias = fit_bias(df)
    ca = knn_cache(df, bias)
    P, Q = fit_mf(df, bias, **BEST_MF)
    n_item = np.bincount(df.i.values, minlength=n_items)
    S = {"Global mean": np.full((n_users, n_items), df.rating.mean(), np.float32),
         "Bias (μ+bᵤ+bᵢ)": bias_scores(bias),
         "Item-kNN (CF)": knn_scores(ca, bias, **BEST_KNN),
         "Matrix factorization (CF)": mf_scores(bias, P, Q)}
    Z = content_z(df)
    S["Hybrid (MF + content)"] = hybrid_scores(S["Matrix factorization (CF)"], Z, n_item, **BEST_HY)
    return dict(bias=bias, P=P, Q=Q, S=S, Z=Z, n_item=n_item)

final = fit_everything(trainval)
S_all, n_trv = final["S"], final["n_item"]
cold_test = n_trv[test.i.values] <= 5
print(f"test ratings on cold movies (<=5 ratings in train+val): {cold_test.sum():,} ({cold_test.mean():.1%})")

rows = []
for name, S in S_all.items():
    rm, ma = rating_metrics(S, test); rc = rating_metrics(S, test, cold_test)[0]
    rows.append((name, rm, ma, rc))
rating_tbl = pd.DataFrame(rows, columns=["Model", "RMSE", "MAE", "RMSE (cold movies)"]).set_index("Model")
print("\n=== Rating prediction on TEST ==="); display(rating_tbl.round(4))

